--- Часы и пауза.
---
--- Время нужно почти каждому: один модуль меряет, сколько узел молчит,
--- другой ждёт между попытками, третий ставит отметку в отчёте. Брать его
--- прямо из ядра нельзя — тогда проверка минутного ожидания занимает
--- минуту, — поэтому время попадает в модуль через набор подменяемых
--- средств. Обёртки для этого набора в каждом модуле выходили одни и те же.
---
--- Здесь они собраны. Пакет даёт умолчания, а не способ подмены: подменяет
--- их всё та же внешняя зависимость, и модуль сам решает, какие из часов ему нужны.
---
--- Стенные часы показывают, который час: их пишут в отчёты и журналы, где
--- важна дата, а не длительность. Их двигает перевод времени и поправка
--- от сервера времени, поэтому ни длительность, ни срок по ним не меряют.
--- Исключение одно — отметка, которая переживает перезапуск процесса или
--- уезжает на другой узел: монотонные часы чужого процесса несравнимы
--- со своими, и остаётся только дата.
---
--- Часы в Tarantool ходят парами, и путать половины пары нельзя: разница
--- между ними не видна, пока файбер не займётся работой, не уступая
--- управления.
---
--- `clock.monotonic()` и `clock.realtime()` спрашивают ядро системы при
--- каждом вызове. Это настоящие часы: монотонные и стенные.
---
--- `fiber.clock()` и `fiber.time()` — не часы, а отметки цикла событий,
--- монотонная и стенная. Обновляются они на обороте цикла — сон, ожидание
--- со сроком, ввод-вывод, `fiber.yield`, — а переключение на уже готовый
--- файбер (`fiber.create`, побудка соседом через `cond` или `channel`) их
--- не двигает. Замер на Tarantool 3.8: цикл на 2·10⁷ сложений без уступки
--- сдвинул `fiber.clock` на 0.000000, а `clock.monotonic` — на 0.090494;
--- после `fiber.yield()` отметки сошлись (0.090552 и 0.090516). Стенная
--- пара ведёт себя так же: 0.09 с работы без уступки сдвинули
--- `fiber.time64` на 0 мкс, а `clock.realtime64` — на 90 002 мкс.
---
--- Но от монотонной отметки отсчитывает срок всякое ожидание: `fiber.sleep`,
--- `cond:wait`, `channel:get` с таймаутом, сокет, `net.box` и `http.client`
--- с таймаутом. Ожидание на `x` секунд кончается в миг «отметка + x», а не
--- «сейчас + x». Опыт: засечка c0 по `clock.monotonic`, 0.089 с работы без
--- уступки, затем `fiber.sleep(c0 + 0.2 - clock.monotonic())` — проснулись
--- через 0.111 с от засечки вместо 0.200. Точка отсчёта у монотонной пары
--- общая — сразу после уступки половины совпадают до микросекунд, — поэтому
--- срок по одной половине и остаток по другой складываются законно.
---
--- Отсюда правило выбора:
---
--- * Длительность — сколько заняло, сколько прошло с последнего ответа,
---   возраст записи — меряется `monotonic`. На отметке цикла всё, что
---   не уступает управления, занимает ноль, а начало, снятое после долгой
---   работы без уступки, завышает длительность на её время.
--- * Срок — это миг, и отмечается он тоже `monotonic`, в миг вызова:
---   `deadline = monotonic() + timeout`. Истёк ли он, решает `monotonic`.
---   Срок, отмеченный `scheduler_now`, отсчитан не от вызова, а от последней
---   уступки вызывающего: его работа без уступки перед вызовом съедает срок.
--- * Остаток срока, который уходит в сон или ожидание, считается от
---   `scheduler_now`: `cond:wait(deadline - scheduler_now())`. Ожидание
---   отсчитает его от той же отметки и кончится ровно в срок — была работа
---   без уступки до вызова или внутри него. Остаток по настоящим часам
---   кончается раньше на всю работу с последнего оборота цикла, и код,
---   не перепроверяющий срок после пробуждения, объявит истечение раньше
---   срока.
--- * Остаток по настоящим часам годится только там, где срок и так
---   перепроверяется после каждого пробуждения: недоспанное доспится
---   следующим оборотом. Так устроено ожидание свободного соединения
---   в пуле — его будят и до срока.
--- * Всякое отступление от правила называется на месте комментарием.
---
--- По цене выбирать нечего: 2 млн вызовов стоят 0.065 с у `fiber.clock`
--- и 0.063 с у `clock.monotonic`.

local fiber = require('fiber')
local clock = require('clock')

local Module = {}

--- Монотонные часы: сколько времени прошло и когда наступает срок.
---
--- Настоящие, а не отметка цикла событий: длительность работы, которая
--- не уступает управления, иначе вышла бы нулевой, а срок отсчитывался бы
--- от последней уступки, а не от вызова.
---@return number Секунды от загрузки машины
function Module.monotonic()
    return clock.monotonic()
end

--- Время планировщика: база остатка срока, который уходит в сон или ожидание.
---
--- Обновляется на обороте цикла событий, а не при каждом вызове, — ровно
--- как отметка, от которой `fiber.sleep` и `cond:wait` отсчитывают свой
--- срок. Ни длительность, ни сам срок им не меряют: работа без уступки
--- по нему занимает ноль, а срок, отмеченный им, отсчитан от последней
--- уступки вызывающего.
---@return number Секунды от той же точки отсчёта, что и у monotonic
function Module.scheduler_now()
    return fiber.clock()
end

--- Монотонные часы целым числом наносекунд.
---
--- Для метрик: секунды в double различают соседние наносекунды, пока часы
--- не ушли за 2²³ с — около 97 суток. Отсчёт у монотонных часов идёт
--- от загрузки машины, и на сервере, работающем дольше, наносекунды теряются
--- с первой секунды жизни узла. int64 держит их всегда.
---@return ffi.cdata* Наносекунды int64 от той же точки отсчёта, что и у monotonic
function Module.monotonic64()
    return clock.monotonic64()
end

--- Стенные часы: который час.
---
--- Настоящие, а не `fiber.time`: тот — отметка цикла событий, и записи,
--- между которыми прошла работа без уступки, получали бы одно время.
---@return number Секунды от начала эпохи
function Module.realtime()
    return clock.realtime()
end

--- Пауза.
---
--- Ждёт именно файбер, а не процесс: остальные в это время работают.
--- Срок паузы отсчитывается от отметки цикла событий, а не от мига вызова:
--- после работы без уступки пауза кончается раньше на её время. Пауза
--- до срока — это `sleep(deadline - scheduler_now())`.
---@param seconds number
function Module.sleep(seconds)
    fiber.sleep(seconds)
end

return Module
